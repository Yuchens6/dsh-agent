import test from "node:test";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { createApiApp } from "../dsh-agent-api/src/app.js";
import { chatClient } from "../dsh-agent-api/src/chat-client.js";
import { createChatApp } from "../dsh-agent-chat/src/app.js";
import { serviceVerifier } from "../dsh-agent-chat/src/auth.js";
import { ChatRepository } from "../dsh-agent-chat/src/repository.js";
import { CatalogRepository } from "../dsh-agent-catalog/src/repository.js";
import { serviceDatabase, definition } from "./workspace-catalog-helpers.js";
import { alice, bob, otherTenant, secret, testBinding } from "./helpers.js";
test("会话生命周期 HTTP：标题、归档恢复、版本竞争、在途回答与原消息幂等", async t => {
 const { pg, db } = await serviceDatabase("chat"); t.after(() => pg.close());
 const repo = new ChatRepository(db, testBinding);
 const chat = createChatApp({ repository: repo, authenticate: serviceVerifier(secret), signCapability: async () => ({}), ready: async () => {} });
 const url = await chat.listen({ host: "127.0.0.1", port: 0 });
 const api = createApiApp({ authenticate: async h => h === "bob" ? bob : alice, chat: chatClient(url, secret) });
 t.after(async () => { await api.close(); await chat.close(); });
 const s = await repo.create(alice, "original", "session-lifecycle", "test");
 const msg = await repo.send(alice, s.id, "pending", "message-lifecycle", "test");
 const patch = (body: unknown, header = "alice") => api.inject({ method: "PATCH", url: "/api/v1/sessions/" + s.id, headers: { authorization: header }, payload: body as Record<string, unknown> });
 assert.equal((await patch({ expectedRevision: 1, title: "renamed" }, "bob")).statusCode, 404);
 const renamed = await patch({ expectedRevision: 1, title: "renamed", archived: true });
 assert.equal(renamed.statusCode, 200, renamed.body); assert.equal(renamed.json().revision, 2);
 assert.equal(renamed.json().archived, true);
 assert.equal((await patch({ expectedRevision: 1, title: "stale" })).statusCode, 409);
 assert.equal((await patch({ expectedRevision: 2, uid: bob.uid })).statusCode, 400);
 await assert.rejects(repo.send(alice, s.id, "new", "message-lifecycle-new", "test"), /INVALID_STATE/);
 assert.equal((await repo.send(alice, s.id, "pending", "message-lifecycle", "test")).id, msg.id);
 await repo.appendAssistant(alice, s.id, { runId: randomUUID(), messageId: msg.id, output: "in-flight answer" });
 assert.equal((await repo.history(alice, s.id, 10)).items.length, 2);
 assert.equal((await patch({ expectedRevision: 2, archived: false })).statusCode, 200);
 await repo.send(alice, s.id, "new", "message-lifecycle-new", "test");
 assert.equal((await repo.get(alice, s.id)).title, "renamed");
 await assert.rejects(repo.update(otherTenant, s.id, { expectedRevision: 3, archived: true }), /NOT_FOUND/);
});
test("Catalog：撤销仅影响指定租户新查询，定义不变，可恢复授权，在线只读账号不能撤销", async t => {
 const { pg, db } = await serviceDatabase("catalog"); t.after(() => pg.close());
 const repo = new CatalogRepository(db);
 await repo.publish(definition, alice.tenantId, true); await repo.publish(definition, otherTenant.tenantId, true);
 await repo.revoke(alice.tenantId, definition.id, 1); await repo.revoke(alice.tenantId, definition.id, 1);
 await assert.rejects(repo.getDefault(alice), /NOT_FOUND/);
 await assert.rejects(repo.get(alice, definition.id, 1), /NOT_FOUND/);
 assert.equal((await repo.getDefault(otherTenant)).id, definition.id);
 assert.equal((await db.query("SELECT * FROM catalog.definitions")).rows.length, 1);
 await repo.publish(definition, alice.tenantId, true);
 await pg.exec("CREATE ROLE catalog_reader; GRANT USAGE ON SCHEMA catalog TO catalog_reader; GRANT SELECT ON ALL TABLES IN SCHEMA catalog TO catalog_reader; SET ROLE catalog_reader");
 await assert.rejects(repo.revoke(alice.tenantId, definition.id, 1), /permission denied/);
 await pg.exec("RESET ROLE");
 assert.equal((await repo.getDefault(alice)).id, definition.id);
});
