const reserve = (actor = alice, outputTokenBudget = 10, runId = randomUUID()) => ({ actor, outputTokenBudget, runId, deadlineAt: new Date(Date.now() + 120_000).toISOString() });
test("Quota：串行预留、用户/租户并发与每日预算、幂等及关闭墓碑", async t => {
 const { db, pg } = await serviceDatabase("quota"); t.after(() => pg.close());
 const quota = new QuotaRepository(db, { userActive: 1, tenantActive: 2, userDailyOutputTokens: 20, tenantDailyOutputTokens: 30 });
 const first = reserve();
 await quota.reserve(first); await quota.reserve(first);
 assert.equal((await quota.usage(alice)).reservedOutputTokensToday, 10);
 await assert.rejects(quota.reserve({ ...first, outputTokenBudget: 11 }), /IDEMPOTENCY_CONFLICT/);
 await assert.rejects(quota.reserve(reserve()), /QUOTA_EXCEEDED/);
 await quota.reserve(reserve(bob));
 await assert.rejects(quota.reserve(reserve({ ...alice, uid: "third" })), /QUOTA_EXCEEDED/);
 await quota.reserve(reserve(otherTenant));
 await assert.rejects(quota.close({ runId: first.runId, actor: bob }), /IDEMPOTENCY_CONFLICT/);
 await quota.close({ runId: first.runId, actor: first.actor });
 await quota.close({ runId: first.runId, actor: first.actor });
 assert.equal((await quota.usage(alice)).active, 0);
 const attempts = await Promise.allSettled([quota.reserve(reserve()), quota.reserve(reserve())]);
 assert.equal(attempts.filter(r => r.status === "fulfilled").length, 1);
 assert.equal((await quota.usage(alice)).reservedOutputTokensToday, 20);
 await db.query("UPDATE quota.reservations SET deadline_at=clock_timestamp()-interval '1 second' WHERE owner_uid=$1", [alice.uid]);
 await assert.rejects(quota.reserve(reserve()), /QUOTA_EXCEEDED/);
 assert.equal((await quota.usage(alice)).active, 0);
 const late = reserve(); await quota.close({ runId: late.runId, actor: alice });
 await assert.rejects(quota.reserve(late), /INVALID_STATE/);
 await assert.rejects(quota.reserve({ ...reserve(), deadlineAt: new Date(Date.now() - 1).toISOString() }), /INVALID_STATE/);
});
test("Audit：元数据白名单、幂等冲突、不可更新/删除/清空与跨租户查询隔离", async t => {
 const { db, pg } = await serviceDatabase("audit"); t.after(() => pg.close());
 const repo = new AuditRepository(db);
 const record = { eventId: randomUUID(), occurredAt: new Date().toISOString(), producer: "dsh-agent-run-control", tenantId: alice.tenantId, ownerUid: alice.uid, runId: randomUUID(), sessionId: randomUUID(), action: "run.accepted" };
 await repo.append(record); await repo.append(record);
 await assert.rejects(repo.append({ ...record, action: "run.started" }), /IDEMPOTENCY_CONFLICT/);
 await assert.rejects(repo.append({ ...record, secret: "not allowed" }));
 assert.equal((await repo.list(alice, { limit: 10 })).items.length, 1);
 assert.equal((await repo.list(bob, { limit: 10 })).items.length, 0);
 assert.equal((await repo.list(otherTenant, { limit: 10 })).items.length, 0);
 for (const sql of ["UPDATE audit.records SET owner_uid='changed'", "DELETE FROM audit.records", "TRUNCATE audit.records"]) await assert.rejects(db.query(sql), /append-only/);
 await pg.exec("CREATE ROLE audit_writer; GRANT USAGE ON SCHEMA audit TO audit_writer; GRANT SELECT,INSERT ON ALL TABLES IN SCHEMA audit TO audit_writer; SET ROLE audit_writer");
 await repo.append({ ...record, eventId: randomUUID() });
 for (const sql of ["UPDATE audit.records SET owner_uid='changed'", "DELETE FROM audit.records", "TRUNCATE audit.records", "ALTER TABLE audit.records DISABLE TRIGGER ALL"]) await assert.rejects(db.query(sql), /permission denied|must be owner/);
 await pg.exec("RESET ROLE");
});
test("支撑服务 HTTP：输入发放前预留、故障关闭、异步审计重传与终态释放", async t => {
 const quotaDb = await serviceDatabase("quota"), auditDb = await serviceDatabase("audit"), runDb = await serviceDatabase("run_control");
 t.after(async () => { await quotaDb.pg.close(); await auditDb.pg.close(); await runDb.pg.close(); });
 const quota = new QuotaRepository(quotaDb.db), audit = new AuditRepository(auditDb.db), runs = new RunRepository(runDb.db);
 const qKey = "test-only-control-quota-secret-32-bytes", aKey = "test-only-control-audit-secret-32-bytes", apiKey = "test-only-api-support-secret-32-bytes";
 const qa = quotaAuth(apiKey, qKey), aa = auditAuth(apiKey, aKey);
 const qApp = createQuotaApp({ repository: quota, authenticateApi: qa.api, authenticateControl: qa.control, ready: async () => {} });
 const aApp = createAuditApp({ repository: audit, authenticateApi: aa.api, authenticateControl: aa.control, ready: async () => {} });
 t.after(async () => { await qApp.close(); await aApp.close(); });
 const quotaUrl = await qApp.listen({ host: "127.0.0.1", port: 0 }), auditUrl = await aApp.listen({ host: "127.0.0.1", port: 0 });
 const support = supportClient({ quotaUrl, auditUrl, quotaSecret: qKey, auditSecret: aKey });
 const messageId = randomUUID(), sessionId = randomUUID();
 const command = { eventId: randomUUID(), eventType: "conversation.message.accepted.v1", producer: "dsh-agent-chat", tenantId: alice.tenantId, ownerUid: alice.uid, sessionId, subjectId: messageId, payload: { messageId }, occurredAt: new Date().toISOString(), traceId: "not in audit" };
 const run = await runs.accept(command); await runs.accept(command);
 const claim = (await runs.claim("worker"))!;
 const input = ExecutionInput.parse({ runId: run.id, capturedAt: new Date().toISOString(), definition, context: { sessionId, messageId, binding: { workspaceId: randomUUID(), agentDefinitionId: definition.id, agentDefinitionVersion: 1 }, truncated: false, messages: [{ id: messageId, sessionId, content: "private prompt", role: "user", createdAt: new Date().toISOString() }] } });
 const bad = supportClient({ quotaUrl, auditUrl, quotaSecret: "wrong-key-with-at-least-thirty-two-bytes", auditSecret: aKey });
 await assert.rejects(runs.input("worker", run.id, claim.lease, async () => input, bad.reserve), /DEPENDENCY_UNAVAILABLE/);
 assert.equal((await runDb.db.query("SELECT execution_input FROM run_control.runs WHERE id=$1", [run.id])).rows[0]!.execution_input, null);
 await runs.input("worker", run.id, claim.lease, async () => input, support.reserve);
 assert.equal((await quota.usage(alice)).reservedOutputTokensToday, 5000);
 assert.equal(await runs.supportBatch(async (kind, payload) => { await support.deliver(kind, payload); throw new Error("ack lost"); }), "retry");
 await runDb.db.query("UPDATE run_control.support_outbox SET next_attempt_at=clock_timestamp()");
 while (await runs.supportBatch(support.deliver) !== "idle") {}
 assert.equal((await audit.list(alice, { limit: 20 })).items.length, 2);
 await runs.finish("worker", run.id, { ...claim.lease, state: "succeeded", output: "private answer" });
 while (await runs.supportBatch(support.deliver) !== "idle") {}
 assert.equal((await quota.usage(alice)).active, 0);
 assert.equal((await quota.usage(alice)).reservedOutputTokensToday, 5000);
 const records = (await audit.list(alice, { limit: 20 })).items;
 assert.equal(records.length, 3); assert.doesNotMatch(JSON.stringify(records), /private|not in audit/);
 const apiToken = await new SignJWT({ actor: alice }).setProtectedHeader({ alg: "HS256" }).setIssuer("dsh-agent-api").setAudience("dsh-agent-quota").setIssuedAt().setExpirationTime("30s").sign(new TextEncoder().encode(apiKey));
 assert.equal((await qApp.inject({ url: "/internal/v1/quota", headers: { authorization: "Bearer " + apiToken } })).statusCode, 200);
 assert.equal((await qApp.inject({ method: "POST", url: "/control/v1/reserve", headers: { authorization: "Bearer " + apiToken }, payload: reserve() })).statusCode, 401);
 assert.equal((await aApp.inject({ url: "/internal/v1/audit", headers: { authorization: "Bearer " + apiToken } })).statusCode, 401);
 const api = createApiApp({ authenticate: async h => h === "bob" ? bob : alice, chat: async () => { throw new Error("unused"); },
   quota: serviceClient(quotaUrl, apiKey, "dsh-agent-quota"), audit: serviceClient(auditUrl, apiKey, "dsh-agent-audit") });
 t.after(() => api.close());
 const usage = await api.inject({ url: "/api/v1/quota" }); assert.equal(usage.statusCode, 200, usage.body);
 assert.equal(usage.json().reservedOutputTokensToday, 5000);
 const auditPage = await api.inject({ url: "/api/v1/audit" }); assert.equal(auditPage.statusCode, 200, auditPage.body); assert.equal(auditPage.json().items.length, 3);
 assert.equal((await api.inject({ url: "/api/v1/audit", headers: { authorization: "bob" } })).json().items.length, 0);
 assert.equal((await api.inject({ url: "/api/v1/audit?ownerUid=bob" })).statusCode, 400);
});
